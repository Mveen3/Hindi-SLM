"""
Supervised Finetuning Dataset (Phase 3)
=======================================

Streams the synthetic reasoning examples generated by
``python main.py reasoning-data`` into batches for supervised finetuning.

This is deliberately *not* the Phase 2 ``LMDataset``. Pretraining packs an
unbroken token stream and trains on every position; reasoning finetuning has a
prompt/answer structure, and training on the prompt would teach the model to
generate questions rather than to answer them. Three differences follow.

**Loss masking.** Each example is ``<s> prompt target </s>``, and only the
*target* positions contribute to the loss. Masked positions are set to
``pad_token_id`` in the label tensor, which the model's own
``F.cross_entropy(..., ignore_index=pad_token_id)`` already skips — so no
change to the Phase 2 model was needed to support this.

**Right padding needs no attention mask.** Sequences in a batch differ in
length, so shorter ones are right-padded. Causal masking already prevents a
real token at position *t* from attending to any position > *t*, so the pad
tokens that sit after it cannot influence it; and the pad positions' own
predictions are masked out of the loss. Left padding would break instead —
learned absolute positional embeddings would shift every real token.

**Length bucketing.** Examples run ~60-450 tokens. Padding a 60-token example
out to 450 would waste most of the batch's compute, so batches are formed from
examples of similar length and only the batch order is shuffled. On the
measured corpus this cuts padding waste from ~2.6x down to ~1.05x.

The whole corpus is tokenized once up front and held in memory: 40k examples at
~150 tokens is a few tens of MB, far cheaper than re-tokenizing every epoch.
"""

from __future__ import annotations

import json
import random

import torch
from torch.utils.data import DataLoader, Dataset
from tokenizers import Tokenizer

from src.languages import Language


class ReasoningSFTDataset(Dataset):
    """One split of the synthetic reasoning corpus, tokenized and masked.

    Args:
        data_path:     JSONL file with ``prompt_text``/``target`` fields.
        tokenizer_path: This language's frozen Phase 1 tokenizer.
        max_seq_len:   Hard cap; longer examples are dropped, not truncated
                       (a truncated chain of thought would train the model on
                       an answer that was cut off).
        pad_token_id:  Padding and loss-ignore index.
        bos_token_id:  Prepended to every prompt.
        eos_token_id:  Appended after every target, so the model learns to stop.
        limit:         Optional cap on examples, for quick smoke runs.
    """

    def __init__(self, data_path, tokenizer_path, max_seq_len: int = 512,
                 pad_token_id: int = 0, bos_token_id: int = 2,
                 eos_token_id: int = 3, limit: int | None = None):
        self.pad_token_id = pad_token_id
        self.max_seq_len = max_seq_len

        tokenizer = Tokenizer.from_file(str(tokenizer_path))

        records = []
        with open(data_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                records.append(json.loads(line))
                if limit and len(records) >= limit:
                    break

        # Batch-encode both halves; the tokenizer's Rust backend makes this
        # far faster than encoding example by example.
        prompt_encodings = tokenizer.encode_batch([r["prompt_text"] for r in records])
        target_encodings = tokenizer.encode_batch([r["target"] for r in records])

        self.examples = []
        self.dropped = 0
        for record, prompt_enc, target_enc in zip(records, prompt_encodings, target_encodings):
            prompt_ids = [bos_token_id] + prompt_enc.ids
            target_ids = target_enc.ids + [eos_token_id]
            full = prompt_ids + target_ids

            if len(full) > max_seq_len:
                self.dropped += 1
                continue

            self.examples.append({
                "full": full,
                "n_prompt": len(prompt_ids),
                "answer": record["answer"],
                "task": record["task"],
                "id": record.get("id", ""),
            })

    def __len__(self) -> int:
        return len(self.examples)

    def lengths(self) -> list[int]:
        """Token length of every example, for the length-bucketing sampler."""
        return [len(e["full"]) for e in self.examples]

    def __getitem__(self, index: int) -> dict:
        """Build the shifted input/label pair with the prompt masked out.

        ``labels[i]`` is the token the model must predict from ``input_ids[i]``.
        Position *i* predicts ``full[i+1]``, which belongs to the target only
        once ``i + 1 >= n_prompt`` — so everything before ``n_prompt - 1`` is
        masked.
        """
        example = self.examples[index]
        full = example["full"]
        n_prompt = example["n_prompt"]

        input_ids = full[:-1]
        labels = list(full[1:])
        for i in range(min(n_prompt - 1, len(labels))):
            labels[i] = self.pad_token_id

        return {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
        }


def collate_padded(batch: list, pad_token_id: int = 0) -> dict:
    """Right-pad a batch to its own longest sequence.

    Padding to the batch maximum rather than to ``max_seq_len`` is what makes
    length bucketing pay off; combined, they keep almost every position in a
    batch a real token.
    """
    max_len = max(item["input_ids"].size(0) for item in batch)

    input_ids = torch.full((len(batch), max_len), pad_token_id, dtype=torch.long)
    labels = torch.full((len(batch), max_len), pad_token_id, dtype=torch.long)

    for i, item in enumerate(batch):
        length = item["input_ids"].size(0)
        input_ids[i, :length] = item["input_ids"]
        labels[i, :length] = item["labels"]

    return {"input_ids": input_ids, "targets": labels}


class LengthBucketSampler(torch.utils.data.Sampler):
    """Yield batches of similarly-sized examples, in a shuffled order.

    Sorting by length groups examples that pad well together; shuffling the
    resulting *batches* (rather than the examples) keeps the gradient signal
    varied across the epoch while preserving that packing.

    Args:
        lengths:    Token length of every example.
        batch_size: Examples per batch.
        shuffle:    Shuffle batch order (and jitter the sort) each epoch.
        seed:       Base seed; the epoch number is mixed in via ``set_epoch``.
    """

    def __init__(self, lengths: list[int], batch_size: int,
                 shuffle: bool = True, seed: int = 42):
        self.lengths = lengths
        self.batch_size = batch_size
        self.shuffle = shuffle
        self.seed = seed
        self.epoch = 0

    def set_epoch(self, epoch: int) -> None:
        """Change the shuffle for a new epoch, so batches are not identical."""
        self.epoch = epoch

    def __iter__(self):
        indices = list(range(len(self.lengths)))
        rng = random.Random(self.seed + self.epoch)

        if self.shuffle:
            # Shuffle first so equal-length examples do not always co-occur,
            # then sort — Python's stable sort preserves the shuffled order
            # within each length.
            rng.shuffle(indices)
        indices.sort(key=lambda i: self.lengths[i])

        batches = [indices[i:i + self.batch_size]
                   for i in range(0, len(indices), self.batch_size)]
        if self.shuffle:
            rng.shuffle(batches)
        return iter(batches)

    def __len__(self) -> int:
        return (len(self.lengths) + self.batch_size - 1) // self.batch_size


def create_finetune_dataloader(lang: Language, split: str, config: dict,
                               shuffle: bool = True, limit: int | None = None):
    """Build a padding-efficient DataLoader over one reasoning split.

    Args:
        lang:    Language whose reasoning corpus and tokenizer to use.
        split:   ``"train"``, ``"val"`` or ``"test"``.
        config:  Merged model + finetuning config.
        shuffle: Shuffle batch order (off for deterministic validation).
        limit:   Optional cap on examples.

    Returns:
        ``(dataloader, dataset)`` — the dataset is returned too so callers can
        report how many examples were loaded or dropped.

    Raises:
        SystemExit: If the split has not been generated yet.
    """
    data_path = lang.reasoning_split_file(split)
    if not data_path.exists():
        raise SystemExit(
            f"{data_path} not found — run "
            f"python main.py reasoning-data --lang {lang.key} first."
        )


    pad_token_id = config.get("pad_token_id", 0)
    dataset = ReasoningSFTDataset(
        data_path=data_path,
        tokenizer_path=lang.tokenizer_path,
        max_seq_len=config.get("max_seq_len", 512),
        pad_token_id=pad_token_id,
        bos_token_id=config.get("bos_token_id", 2),
        eos_token_id=config.get("eos_token_id", 3),
        limit=limit,
    )

    sampler = LengthBucketSampler(
        lengths=dataset.lengths(),
        batch_size=config["batch_size"],
        shuffle=shuffle,
        seed=config.get("seed", 42),
    )

    loader = DataLoader(
        dataset,
        batch_sampler=sampler,
        collate_fn=lambda b: collate_padded(b, pad_token_id),
        num_workers=config.get("num_workers", 2),
        pin_memory=torch.cuda.is_available(),
    )
    return loader, dataset
